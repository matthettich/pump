#!/bin/sh
# Builds pump.wasm (the nine mastering engines and the creative effects behind wasm/pump_wasm.cpp's C interface, for Thunder Plus's track effects) and
# pump-meta.js (every plugin's parameter table and factory presets, from the same Params.hpp tables), into OUT; and
# pump-synth.wasm (the instruments MONO, POLY and COIL behind wasm/pump_synth.cpp, for Thunder Plus's synth engines)
# with pump-synth-meta.js (their parameters and factory presets).
#
# Toolchain: wasi-sdk 25 (https://github.com/WebAssembly/wasi-sdk/releases/download/wasi-sdk-25/
# wasi-sdk-25.0-x86_64-linux.tar.gz), WASI_SDK = its folder; a host C++ compiler (c++) for the meta table.
# No threads in an AudioWorklet: -DPUMP_SYNC_KERNELS=1 (see common/dsp/Util.hpp). Same optimisation as the plugins
# (DPF: -O3 -ffast-math; pump: -fno-finite-math-only), plus wasm SIMD (pffft's pf_wasm_float.h).
#
# Usage: WASI_SDK=/path/to/wasi-sdk-25.0-x86_64-linux sh wasm/build.sh [OUT]   (OUT defaults to build/wasm)
#        then copy OUT/pump.wasm and OUT/pump-meta.js to thunder-plus/pump/, OUT/pump-synth.wasm and
#        OUT/pump-synth-meta.js to thunder-plus/pump/synth/, and bump their ?v= there.
set -e
H=$(cd "$(dirname "$0")/.." && pwd)
OUT=${1:-$H/build/wasm}
mkdir -p "$OUT"
[ -x "$WASI_SDK/bin/clang++" ] || { echo "set WASI_SDK to the wasi-sdk 25 folder"; exit 1; }
FLAGS="--target=wasm32-wasip1 --sysroot=$WASI_SDK/share/wasi-sysroot -O3 -ffast-math -fno-finite-math-only -msimd128 -DPUMP_SYNC_KERNELS=1 -DPFFFT_STATIC_DEFINE -DNDEBUG"
O=$(mktemp -d)
"$WASI_SDK/bin/clang" $FLAGS -Wno-everything -c "$H/common/pump_pffft.c" -I"$H/common" -o "$O/pffft.o"
"$WASI_SDK/bin/clang++" $FLAGS -std=c++17 -fno-exceptions -fno-rtti -Wall -Wno-unused-parameter -Wno-unused-private-field -I"$H/common" -c "$H/wasm/pump_wasm.cpp" -o "$O/pump.o"
# the creative effects: each plugin's own Plugin<Name>.hpp, one translation unit each, on the DPF stand-in (wasm/shim
# before common, so PumpPlugin.hpp's #include "DistrhoPlugin.hpp" finds it; the plugin's folder for its DistrhoPluginInfo.h)
FXO=""
for p in tube snap gate echo spring verb grain vox tune crush swirl stutter chop twang; do
  "$WASI_SDK/bin/clang++" $FLAGS -std=c++17 -fno-exceptions -fno-rtti -Wno-everything -I"$H/wasm/shim" -I"$H/plugins/$p" -I"$H/common" -c "$H/wasm/fx/$p.cpp" -o "$O/fx_$p.o"
  FXO="$FXO $O/fx_$p.o"
done
EXPORTS=""
for f in pump_types pump_nparams pump_stage pump_new pump_free pump_values pump_commit pump_io pump_process pump_latency \
         pump_tel pump_tel_len pump_rings pump_ring_pos pump_ring_cap pump_ring_read pump_hold \
         pump_midi pump_transport pump_text pump_state_get pump_state_set; do EXPORTS="$EXPORTS -Wl,--export=$f"; done
"$WASI_SDK/bin/clang++" $FLAGS -mexec-model=reactor -Wl,--export=_initialize $EXPORTS -Wl,--strip-all -Wl,-z,stack-size=1048576 \
  -Wl,--initial-memory=16777216 "$O/pump.o" $FXO "$O/pffft.o" -o "$OUT/pump.wasm"
# the instruments: no input audio, MIDI in (pump_synth.cpp); COIL's tanks are SPRING's (its own SIMD, no pffft)
"$WASI_SDK/bin/clang++" $FLAGS -std=c++17 -fno-exceptions -fno-rtti -Wall -Wno-unused-parameter -Wno-unused-private-field -I"$H/common" -c "$H/wasm/pump_synth.cpp" -o "$O/synth.o"
SEXPORTS=""
for f in psyn_types psyn_nparams psyn_stage psyn_new psyn_free psyn_values psyn_commit psyn_midi psyn_out psyn_process psyn_latency; do SEXPORTS="$SEXPORTS -Wl,--export=$f"; done
"$WASI_SDK/bin/clang++" $FLAGS -mexec-model=reactor -Wl,--export=_initialize $SEXPORTS -Wl,--strip-all -Wl,-z,stack-size=1048576 \
  -Wl,--initial-memory=16777216 "$O/synth.o" -o "$OUT/pump-synth.wasm"
# the parameter and preset tables, from the plugins' own headers
${CXX:-c++} -std=c++17 -O1 -I"$H/common" "$H/wasm/pump_meta.cpp" -o "$O/pump_meta"
"$O/pump_meta" > "$O/meta.json"
python3 - "$O/meta.json" "$H/plugins" "$OUT/pump-meta.js" <<'PY'
import json, re, sys, os, hashlib
meta = json.load(open(sys.argv[1]))
for k in meta['types']:
    info = open(os.path.join(sys.argv[2], k, 'DistrhoPluginInfo.h')).read()
    m = re.search(r'#define PUMP_PLUGIN_ABOUT\s+"((?:[^"\\]|\\.)*)"', info)
    meta['fx'][k]['about'] = m.group(1) if m else ''
src = json.dumps(meta, separators=(',', ':'), ensure_ascii=False)
open(sys.argv[3], 'w').write('// Generated by pump/wasm/build.sh from the plugins\' Params.hpp tables: do not edit by hand.\n'
                             '// sha1 ' + hashlib.sha1(src.encode()).hexdigest() + '\nglobalThis.PUMP_META = ' + src + ';\n')
PY
"$O/pump_meta" synth > "$O/synth-meta.json"
python3 - "$O/synth-meta.json" "$H/plugins" "$OUT/pump-synth-meta.js" <<'PY'
import json, re, sys, os, hashlib
meta = json.load(open(sys.argv[1]))
for k in meta['types']:
    info = open(os.path.join(sys.argv[2], k, 'DistrhoPluginInfo.h')).read()
    m = re.search(r'#define PUMP_PLUGIN_ABOUT\s+"((?:[^"\\]|\\.)*)"', info)
    meta['synth'][k]['about'] = m.group(1) if m else ''
src = json.dumps(meta, separators=(',', ':'), ensure_ascii=False)
open(sys.argv[3], 'w').write('// Generated by pump/wasm/build.sh from the instruments\' Params.hpp tables: do not edit by hand.\n'
                             '// sha1 ' + hashlib.sha1(src.encode()).hexdigest() + '\nglobalThis.PUMP_SYNTH_META = ' + src + ';\n')
PY
rm -rf "$O"
ls -l "$OUT/pump.wasm" "$OUT/pump-meta.js" "$OUT/pump-synth.wasm" "$OUT/pump-synth-meta.js"
