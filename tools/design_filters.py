"""Designs the fixed FIR filters used by the pump DSP library and writes common/dsp/FilterTables.hpp.

- Linear-phase halfband stages for 2x/4x/8x oversampling (Parks-McClellan). Stage 1 carries the steep
  transition (passband to 0.4535 fs, i.e. 20 kHz at 44.1 kHz); later stages only reject images of a signal
  already band-limited by stage 1, so they are short.
- A 4x interpolator for true-peak detection (ITU-R BS.1770 style, but steeper: passband to 20 kHz at 44.1 kHz,
  >= 70 dB image rejection).

Run: python3 tools/design_filters.py   (needs numpy + scipy)"""
import numpy as np
from scipy.signal import remez, freqz
import os

def halfband(ntaps, fp, weight_stop=1.0):
    """ntaps = 4k+3. fp = passband edge as a fraction of the OUTPUT rate (< 0.25). Returns taps with exact zeros."""
    assert ntaps % 4 == 3
    h = remez(ntaps, [0, fp, 0.5 - fp, 0.5], [1, 0], weight=[1, weight_stop], fs=1.0)
    c = (ntaps - 1) // 2
    for i in range(ntaps):
        if (i - c) % 2 == 0 and i != c:
            h[i] = 0.0
    h[c] = 0.5
    return h

def report(name, h, fp, fs_edge, rate=1.0):
    w, H = freqz(h, worN=1 << 16, fs=rate)
    Hn = np.abs(H) / np.abs(H[0])
    pb = Hn[w <= fp]
    sb = Hn[w >= fs_edge]
    print(f"{name}: {len(h)} taps, passband ripple {20*np.log10(pb.max()):+.5f}/{20*np.log10(pb.min()):+.5f} dB, "
          f"stopband {20*np.log10(sb.max()+1e-30):.1f} dB")

out = []
# Stage 1: steep. At output rate 2fs, passband 0.4535 fs = 0.22675 of output rate.
h1 = halfband(127, 0.22675)
report('HB1', h1, 0.22675, 0.27325)
# Stage 2: input content already limited to ~0.5465 fs (stage-1 stopband). At output rate 4fs:
# passband 0.4535/4 = 0.1134, images start at (2 - 0.5465)/4 = 0.3634.
h2 = halfband(23, 0.1134)
report('HB2', h2, 0.1134, 0.3866)
# Stage 3: at 8fs: passband 0.0567, stop from (4 - 0.5465)/8 = 0.4317 -> (0.5 - 0.0567)
h3 = halfband(11, 0.0567)
report('HB3', h3, 0.0567, 0.4433)

# True-peak 4x interpolator (polyphase: 4 phases). Normalised to the 4x rate.
ntp = 192
tp = remez(ntp, [0, 0.4535 / 4, 0.5465 / 4, 0.5], [1, 0], weight=[1, 30], fs=1.0)
tp = tp * 4.0 / tp.sum()   # unity DC gain per phase
report('TP4', tp / 4.0, 0.4535 / 4, 0.5465 / 4)
phases = [tp[p::4] for p in range(4)]

def arr(name, v):
    s = ', '.join(f'{x:.17g}' for x in v)
    return f'static constexpr double {name}[{len(v)}] = {{ {s} }};\n'

with open(os.path.join(os.path.dirname(__file__), '..', 'common', 'dsp', 'FilterTables.hpp'), 'w') as f:
    f.write('// Generated by tools/design_filters.py. Do not edit by hand.\n#pragma once\n\nnamespace pump { namespace tables {\n\n')
    for n, h in (('kHB1', h1), ('kHB2', h2), ('kHB3', h3)):
        f.write(arr(n, h))
    f.write(f'static constexpr int kTPPhaseLen = {len(phases[0])};\n')
    for p in range(4):
        f.write(arr(f'kTP{p}', phases[p]))
    f.write('\n}} // namespace pump::tables\n')
print('written')
