"""Subsets the UI fonts and embeds them as C arrays in common/ui/FontData.cpp (+ FontData.hpp).

Share Tech Mono (labels; the Simple skins' font) is kept whole; JetBrains Mono Regular/Bold (numbers and
symbols) are subset to Latin-1 plus the symbols the UI draws. Run: python3 tools/embed_fonts.py"""
import os, io
from fontTools import subset
from fontTools.ttLib import TTFont

here = os.path.dirname(os.path.abspath(__file__))
fonts = os.path.join(here, '..', 'common', 'fonts')
out_dir = os.path.join(here, '..', 'common', 'ui')

symbols = '…·•→←↑↓▲▼◀▶×−±∞°√∑µΔ█▏▕▁▂▃▄▅▆▇◆○●◉✓✕↺⟲⇄'
unicodes = list(range(0x20, 0x7f)) + list(range(0xa0, 0x100)) + [ord(c) for c in symbols]

def load(name, sub):
    path = os.path.join(fonts, name)
    if not sub:
        return open(path, 'rb').read()
    f = TTFont(path)
    opts = subset.Options()
    opts.layout_features = []
    opts.hinting = False
    opts.desubroutinize = True
    s = subset.Subsetter(opts)
    s.populate(unicodes=unicodes)
    s.subset(f)
    b = io.BytesIO()
    f.save(b)
    return b.getvalue()

items = [
    ('kFontLabel', 'ShareTechMono-Regular.ttf', False),
    ('kFontMono', 'JetBrainsMono-Regular.ttf', True),
    ('kFontMonoBold', 'JetBrainsMono-Bold.ttf', True),
]

with open(os.path.join(out_dir, 'FontData.hpp'), 'w') as h:
    h.write('// Generated by tools/embed_fonts.py. Fonts: Share Tech Mono and JetBrains Mono (SIL OFL 1.1).\n#pragma once\n\nnamespace pump { namespace fonts {\n')
    for sym, _, _ in items:
        h.write(f'extern const unsigned char {sym}[];\nextern const unsigned int {sym}Size;\n')
    h.write('}} // namespace pump::fonts\n')

with open(os.path.join(out_dir, 'FontData.cpp'), 'w') as c:
    c.write('// Generated by tools/embed_fonts.py. Do not edit.\n#include "FontData.hpp"\n\nnamespace pump { namespace fonts {\n')
    for sym, fn, sub in items:
        data = load(fn, sub)
        c.write(f'const unsigned int {sym}Size = {len(data)};\nconst unsigned char {sym}[] = {{\n')
        for i in range(0, len(data), 24):
            c.write(','.join(str(b) for b in data[i:i + 24]) + ',\n')
        c.write('};\n')
        print(fn, len(data), 'bytes')
    c.write('}} // namespace pump::fonts\n')
